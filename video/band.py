"""
입장 밴드(밴딩) 인쇄용 원고 — GUEST · VIP · VVIP · STAFF 4종.

    크기   3000 × 300 px = 254 × 25 mm @300dpi (타이벡 밴드 표준)
    출력   out/band/band_{guest,vip,vvip,staff}.png

밴드는 포스터가 아닙니다. 25mm 짜리 띠에서 지켜야 하는 게 따로 있습니다.

**0. 바탕은 흑백, 색은 VIP·VVIP 에만**
   포스터에 준 컬러 예외는 **행사 모객용**에만 해당합니다. 밴드는 손님이
   행사 내내 차고 다니는 **브랜드 접점**이라 크루 톤을 따릅니다.
   흑백 · 여백 넓게 · 미니멀. "국내 동호회가 아니라 해외 DJ 브랜드처럼."

   다만 VIP·VVIP 는 돈을 더 낸 자리라 한눈에 갈려야 합니다.
   **GUEST(검정)·STAFF(흰색)를 무채색으로 두고 가운데 둘에만 색을 얹으면,
   색 자체가 '특별함'을 뜻하게 됩니다.** 넷 다 색을 주면 그냥 알록달록한
   밴드가 되고 등급의 의미가 사라집니다.
   색은 행사 이름에서 가져왔습니다 — AFTER SUNSET, 해가 진 뒤의 노을.
   VIP 는 식은 노을의 와인빛(마르살라), VVIP 는 샴페인 골드.
   **채도는 낮게 갑니다** — 쨍한 색을 25mm 에 꽉 채우면 놀이공원 팔찌가 됩니다.

**1. 그래도 등급은 명도와 개수로도 나눈다**
   색만 믿지 않습니다. **밝기 네 단**과 **세는 막대**를 그대로 둡니다 —
   GUEST 1 · VIP 2 · VVIP 3 · STAFF 4.
   밤이고 조명이 흔들려도 개수는 셀 수 있습니다. 색약도 문제가 안 됩니다.
   등급 표기는 영문으로 통일합니다. '일반'·'직원'을 섞으면 밴드가 안내문이 됩니다.

**2-1. 위아래 가로선은 뺐다**
   장식 괘선이었는데 가장자리와 나란해서 재단선으로 오해를 샀습니다.
   그 자리에 협업 브랜드 줄을 넣었다가 그것도 뺐습니다 — 손목에 감기는
   물건에서 실제로 읽히는 건 등급과 이름뿐이고, 나머지는 밴드를 협찬
   스티커로 보이게 만들었습니다. **한 줄만 남기니 세로 가운데가 기준이 됩니다.**
   진짜 재단·블리드는 인쇄소 사양에 맞춰 그쪽에서 잡습니다.

**3. 한 번에 3분의 1도 안 보인다 — 그래서 등급만 더 자주 반복한다**
   손목에 감기니까 같은 덩어리를 두 번 반복합니다. 접착 탭이 한쪽 반복을
   덮어도 나머지 하나가 통째로 남습니다.

   다만 **꼭 보여야 하는 건 등급 하나뿐**입니다. 이름은 두 번이면 충분하지만
   등급은 어느 각도에서든 잡혀야 합니다. 그래서 덩어리 앞머리에 **막대만**
   한 벌 더 둡니다 — 낱말 없이 막대만이라 자리를 거의 안 먹고,
   등급 신호는 밴드 하나에 네 번 나타납니다(칩 2 + 막대 2).

**3-1. 어두운 데서는 눈이 색이 아니라 밝기를 본다**
   어두우면 망막의 간상체가 일을 하는데, 간상체는 색을 못 봅니다.
   **주변시로 스쳐 볼 때 눈에 걸리는 건 색이 아니라 밝기 대비**입니다.
   그래서 밴드마다 **가장 밝기 대비가 큰 덩어리(칩)를 딱 하나** 둡니다.
   나머지는 조용히 둡니다 — 눈에 띄는 것이 둘이면 둘 다 안 띕니다.

**3-2. 밤에는 붉은색이 실제보다 훨씬 어두워 보인다**
   어두워지면 눈의 민감도가 푸른-초록 쪽으로 옮겨 갑니다(푸르키니에 현상).
   낮에 선명하던 붉은색이 밤에는 검게 가라앉습니다.
   그래서 VIP 의 마르살라는 **바탕색만 믿지 않습니다** — 밝은 칩이 대신 눈에 걸립니다.
   샴페인(VVIP)은 초록 성분이 많아 밤에도 덜 죽습니다.

**4. 밴드에 없어도 되는 건 전부 뺀다**
   남긴 것 — 크루 이름(BLACKOUT) · 등급. 둘뿐이다.
   뺀 것과 이유:
       행사 이름(AFTER SUNSET) 밴드는 다음 행사에도 쓴다. 크루명이 남아야 한다.
       형식(풀파티×솔로파티)   행사 이름조차 뺐다. 더 말할 것도 없다.
       시간(19:00–24:00)      밴드를 찬 사람은 이미 들어와 있다. 필요 없다.
       장소·주소              마찬가지. 도착한 사람에게 주소는 정보가 아니다.
       날짜(08.29 SAT)        하루짜리 행사다. 그날 그 자리에서만 쓰는 밴드에
                              날짜를 적는 건 자기 자신을 설명하는 것이다.
   **뺄 것을 정하는 게 이 판의 설계입니다.** 25mm 안에서 층이 늘어날수록
   전부 같은 크기가 되고, 같은 크기면 아무것도 안 읽힙니다.

**4-1. 크기·자간·여백을 눈대중으로 고르지 않는다**
   크기는 하나의 기준(18)과 비율(1.30)에서 뽑습니다 — 18 · 23 · 30 · 40 · 51.
   서로 관계가 있는 숫자라야 넷이 한 판으로 읽힙니다.
   자간은 **크기에 반비례**합니다. 작은 글자일수록 벌려야 읽히고, 큰 글자에
   같은 자간을 주면 흩어집니다. 여백은 한 단위(16px)의 배수로만 씁니다 —
   `U` 하나만 바꾸면 판 전체의 숨이 같이 바뀝니다.

**5. 재단 여유(±1mm)를 먹고 들어간다**
   위아래 4mm(=48px, `SAFE`)는 비웁니다. 여기 글자를 걸면 잘려 나옵니다.

**6. 베이스라인을 공유한다**
   왼쪽 이름 블록과 오른쪽 날짜 블록은 글자 크기가 다릅니다. 각각 가운데를
   맞추면 두 덩어리가 서로 다른 높이에 뜬 것처럼 보입니다.

**7. 가르는 선은 고정 좌표로 박지 않는다**
   남는 폭 한가운데에 둡니다. 박아 두면 글자 길이가 바뀔 때 한쪽에 붙습니다.

**8. 위아래 선은 캔버스 전체에 한 번에 긋는다**
   덩어리마다 그리면 이음새에서 1px 어긋난 게 띠 전체에 줄로 보입니다.

인쇄 넘길 때
    · RGB PNG 입니다. CMYK 변환은 인쇄소에 맡기세요.
    · 접착 탭(끝 약 9mm)은 겹쳐 붙는 자리라 비워 뒀습니다.
      **감으면 이 탭이 반대쪽 시작을 덮습니다** — 그래서 두 번 반복합니다.
    · 가장 가는 선이 3px(=0.25mm)입니다. 이보다 얇게 고치지 마세요 — 인쇄에서 사라집니다.
    · 일련번호가 필요하면 인쇄소 넘버링 옵션으로. 여기서 그리면 전부 같은 번호입니다.
    · VVIP 의 샴페인은 **잉크 색**입니다. 진짜 금박을 원하면 인쇄소에 후가공(박)을
      따로 요청하세요 — 채도를 낮춰 뒀으니 박으로 바꿔도 판이 안 흔들립니다.
    · 그라데이션은 넣지 않았습니다. 25mm 폭에서 타이벡 인쇄는 계조가 뭉개집니다.

python band.py  →  out/band/band_{guest,vip,vvip,staff}.png
"""
import os
import numpy as np
from PIL import Image
from poster_kit import BRAND, tmask_bl, fit, paint, paint_bl, box, logo, grain
import event as EV

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'out', 'band')
os.makedirs(OUT, exist_ok=True)

W, H = 3000, 300                       # 254 × 25 mm @300dpi
SAFE = 48                              # 재단 여유 4mm. 이 안쪽에만 그린다
TAB = int(W * 0.035)                   # 접착 탭 — 겹쳐 붙는 자리
# 덩어리 폭은 **탭을 뺀 폭**에서 나눈다. 전체 폭으로 나눈 뒤 탭을 덧칠하면
# 두 번째 덩어리의 오른쪽 글자가 잘려 나간다 — 실제로 그렇게 잘렸다.
PRINT = W - TAB
UNIT = PRINT // 2
HAIR = 3                               # 최소 획 3px = 0.25mm. 더 얇으면 인쇄에서 사라진다

# 두 줄의 베이스라인. 형식·시간을 빼면서 줄이 하나 줄었고, 그만큼 이름을 키웠다.
# ── 타이포 체계 ───────────────────────────────────────────
# 크기를 눈대중으로 고르면 넷이 서로 아무 관계가 없어 보인다.
# **하나의 기준(BASE)과 비율(RATIO)에서 전부 뽑는다.**
BASE, RATIO = 18, 1.30


def step(n):
    return int(round(BASE * RATIO ** n))          # 18 · 23 · 30 · 40 · 51


def track(size):
    """자간은 크기에 **반비례**한다.

    작은 글자일수록 더 벌려야 읽히고, 큰 글자에 같은 자간을 주면 흩어져 보인다.
    처음엔 이게 거꾸로 들어가 있었다 — 제일 작은 협업 브랜드 줄의 자간이
    제일 좁았고, 그래서 25mm 에서 뭉쳐 보였다."""
    return round(0.34 - size * 0.0040, 3)         # 18→0.268 · 30→0.220 · 51→0.136


U = 16                                            # 여백 한 단위. 이것만 바꾸면 판 전체 숨이 같이 바뀐다
CY = H / 2                                        # 세로 가운데. 한 줄이 된 뒤로 모든 게 여기에 맞는다

# **행사 이름이 아니라 크루 이름을 넣는다.** 밴드는 그날 하루가 아니라
# 다음 행사에도 쓰는 물건이고, 손님이 차고 다니는 브랜드 접점이다 —
# 행사명을 박으면 그 행사 기념품이 되고, 크루명을 박으면 크루가 남는다.
BAND_NAME = 'BLACKOUT'

INK   = np.array([0.05, 0.05, 0.06], np.float32)
PAPER = np.array([0.96, 0.96, 0.95], np.float32)

# **VIP · VVIP 만 색을 쓴다.** 브랜드는 흑백이지만 이 둘은 돈을 더 낸 자리라
# 한눈에 갈려야 합니다. GUEST(검정)·STAFF(흰색)는 무채색으로 두고
# 가운데 둘만 색을 얹으면, 색이 곧 '특별함'을 뜻하게 됩니다.
#
# **촌스러움은 색상이 아니라 채도에서 옵니다.** 처음엔 형광에 가까운 로즈(채도
# 0.76)와 금색(0.84)이었고, 25mm 띠를 그 채도로 꽉 채우니 행사 밴드가 아니라
# 놀이공원 팔찌로 읽혔습니다. 채도를 내리고 **등급은 명도로 가릅니다** —
# 어두운 데서 눈에 걸리는 건 어차피 색이 아니라 밝기 대비입니다(아래 3-1).
#
# 색은 그대로 행사 이름에서 옵니다. AFTER SUNSET — 해가 진 뒤에 남는 건
# 쨍한 노을이 아니라 **가라앉은 와인빛과 금속**입니다.
#     VIP  마르살라 — 노을이 식은 뒤의 짙은 자줏빛 붉은색
#     VVIP 샴페인 골드 — 쨍한 노랑이 아니라 빛을 머금은 금속
MARSALA = np.array([0.55, 0.24, 0.28], np.float32)   # 채도 0.56 · 색상 352°
CHAMP   = np.array([0.80, 0.71, 0.54], np.float32)   # 채도 0.33 · 색상 41°

# (등급, 막대 수, 배경, 글자) — 밝기 네 단으로 계단은 그대로 유지한다
TIERS = [
    ('GUEST', 1, INK,   PAPER),
    ('VIP',   2, MARSALA, PAPER),
    ('VVIP',  3, CHAMP,   INK),
    ('STAFF', 4, PAPER, INK),
]


def tier_chip(u, word, n, bg, fg):
    """오른쪽 끝 등급 표시.

    **문에서 제일 먼저 확인하는 게 등급입니다.** 그런데 처음엔 밴드에서 제일
    작은 글자였습니다 — 이름·날짜보다 작으면 기능을 못 합니다.
    키우되 이름을 넘지는 않게, 그 사이에서 잡습니다.

    색을 못 믿는 상황(밤·조명·색약)을 위해 **세는 막대**를 같이 넣습니다.
    막대 수가 곧 출입 등급이라 문에서 세기만 하면 됩니다."""
    ws = step(2)
    wm = tmask_bl(word, BRAND, ws, track(ws))
    bw = gap = U - 6
    bars_w = n * bw + (n - 1) * gap
    pad = U * 2
    cw = pad + bars_w + int(U * 1.5) + wm[0].shape[1] + pad
    x1 = UNIT - U * 5
    x0 = x1 - cw
    # **칩도 세로 가운데에 앉힌다.** 베이스라인에서 잰 값으로 두면
    # 상자가 글자보다 위로 뜬다 — 눈에는 그게 '삐뚤다' 로 보인다
    ch = U * 5.125                                   # 칩 높이는 그대로
    y0, y1 = CY - ch / 2, CY + ch / 2
    box(u, x0, y0, x1, y1, fg)                       # 칩은 글자색으로 채운다(반전)
    bx = x0 + pad
    for i in range(n):
        box(u, bx + i * (bw + gap), y0 + U, bx + i * (bw + gap) + bw, y1 - U, bg)
    # 칩 안에서도 글자는 광학 중심에 — 상자 정가운데로 두면 아래로 처져 보인다
    paint_bl(u, wm, x1 - pad, (y0 + y1) / 2 + wm[0].shape[0] * 0.5, color=bg, anchor='r')
    return x0


def tier_marks(u, n, fg, x, cy):
    """낱말 없이 막대만. 등급 신호를 밴드 하나에 네 번 나타나게 하는 값싼 방법.

    막대 자리는 **등급과 상관없이 폭을 고정**한다(4개 기준). 개수에 따라 폭이
    달라지면 밴드마다 로고 위치가 어긋나 네 종이 다른 판처럼 보인다."""
    bw = gap = U - 6
    for i in range(n):
        box(u, x + i * (bw + gap), cy - U * 1.6, x + i * (bw + gap) + bw, cy + U * 1.6, fg, 0.85)
    return x + 4 * bw + 3 * gap                      # 항상 4개분을 비워 둔다


def draw_unit(u, bg, fg, word, n):
    """한 덩어리. **줄이 하나뿐이라 전부 세로 가운데에 맞춘다.**

    협업 브랜드 줄을 빼면서 두 줄이 한 줄이 됐는데, 베이스라인 값(150)은
    두 줄 시절 그대로였다 — 그 바람에 로고도 글자도 칩도 다 위로 떠 있었다.
    이제 셋 다 `CY` 를 기준으로 앉는다.

    **글자는 베이스라인, 그림은 가운데** 라 기준이 다르다. 대문자 글자는
    마스크 높이가 곧 캡 높이라 `CY + 높이/2` 가 광학 중심이 된다."""
    u[:] = bg

    # ── 왼쪽부터 — 막대 · 로고 · 이름 ─────────────────────
    x = U * 6
    x = tier_marks(u, n, fg, x, CY) + U * 2

    lg = logo(U * 6)
    # 엠블럼은 좌우가 비대칭이라 상자 가운데로 맞추면 살짝 처져 보인다. 조금 올린다
    paint(u, lg, x, CY - U * 0.15, color=fg, a=0.95)
    x += lg.shape[1] + U * 3

    # 등급 낱말 길이가 달라(GUEST · VIP · VVIP · STAFF) 칩 폭이 등급마다 다르다.
    # 이름을 고정 크기로 두면 칩이 넓은 등급에서 겹친다 —
    # **오른쪽부터 자리를 잡고 이름을 역산한다.**
    chip_x = tier_chip(u, word, n, bg, fg)

    # 자간을 넓게 준다. 브랜드 톤이 '여백 넓게'라 밴드에서도 글자를 붙이지 않는다
    ns = min(step(4), fit(BAND_NAME, BRAND, chip_x - U * 8 - x, track(step(4))))
    name = tmask_bl(BAND_NAME, BRAND, ns, track(ns))
    # 대문자라 마스크 높이 = 캡 높이. 절반을 내리면 광학 중심에 앉는다
    paint_bl(u, name, x, CY + name[0].shape[0] / 2, color=fg)


def build(word, n, bg, fg):
    img = np.zeros((H, W, 3), np.float32)
    u = np.zeros((H, UNIT, 3), np.float32)
    draw_unit(u, bg, fg, word, n)
    img[:, :UNIT] = u
    img[:, UNIT:UNIT * 2] = u
    img[:, UNIT * 2:] = bg          # 나머지는 탭까지 바탕으로

    box(img, W - TAB, 0, W, H, bg)         # 접착 탭은 바탕만
    grain(img, 0.006, 2)
    return np.clip(img, 0, 1)


def save(img, name):
    p = os.path.join(OUT, f'{name}.png')
    Image.fromarray((np.clip(img, 0, 1) * 255).astype(np.uint8)).save(p, optimize=True)
    lum = float((img @ np.float32([0.299, 0.587, 0.114])).mean())
    print(f'{p}  {W}×{H}px ≈254×25mm@300dpi  평균밝기 {lum:.2f}')


if __name__ == '__main__':
    for word, n, bg, fg in TIERS:
        save(build(word, n, bg, fg), f'band_{word.lower()}')
